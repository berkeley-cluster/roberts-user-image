              library = lib, prompt = FALSE)
renv::install(c(cran, bioc), library = lib, prompt = FALSE)

# Fail the build if anything is missing or not at its pinned version
spec <- sub("^bioc::", "", c(cran, bioc))
pins <- setNames(sub(".*@", "", spec), sub("@.*", "", spec))
have <- installed.packages()[, "Version"]
missing <- setdiff(names(pins), names(have))
if (length(missing)) stop("not installed: ", paste(missing, collapse = ", "))
wrong <- names(pins)[have[names(pins)] != pins]
if (length(wrong)) {
  stop("version differs from pin: ",
       paste0(wrong, " ", have[wrong], " (pinned ", pins[wrong], ")",
              collapse = ", "))
}
cat(length(cran) + length(bioc), "packages installed\n")
